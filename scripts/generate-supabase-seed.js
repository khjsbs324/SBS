const fs = require('fs');
const path = require('path');

global.window = {};
require(path.resolve(__dirname, '../data/curriculum-data.js'));
require(path.resolve(__dirname, '../data/site-data.js'));

const curriculum = window.SBSCurriculumData;
const site = window.SBSSiteData;
const outputPath = path.resolve(__dirname, '../supabase/seed.sql');

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const nullable = (value) => value == null ? 'null' : quote(value);
const boolean = (value) => value ? 'true' : 'false';
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const textArray = (items) => `array[${items.map(quote).join(', ')}]::text[]`;

const parentBySlug = {
    ai_agent_basic: 'ai_agent',
    ai_agent_advanced: 'ai_agent',
    cert_oa: 'cert',
    cert_field: 'cert'
};

const topLevelOrder = [
    'design_basic',
    'webtoon',
    'artwork',
    'ai_agent',
    'uiux',
    'ai_sw',
    'visual',
    'archi',
    'motion',
    'cg_vfx',
    'youtube',
    'product_cert',
    'senior',
    'cert',
    'national'
];

const syntheticCategories = {
    ai_agent: 'AI에이전트',
    cert: '자격증'
};

const categoryRows = topLevelOrder.map((slug, index) => ({
    slug,
    parentSlug: null,
    name: syntheticCategories[slug] || curriculum.categoryNames[slug],
    flow: curriculum.courseFlowData[slug] || '',
    sortOrder: index
}));

for (const [slug, parentSlug] of Object.entries(parentBySlug)) {
    categoryRows.push({
        slug,
        parentSlug,
        name: curriculum.categoryNames[slug],
        flow: curriculum.courseFlowData[slug] || '',
        sortOrder: Object.keys(parentBySlug).filter((key) => parentBySlug[key] === parentSlug).indexOf(slug)
    });
}

const courseNames = [];
const courseNameSet = new Set();
const addCourse = (name) => {
    if (!courseNameSet.has(name)) {
        courseNameSet.add(name);
        courseNames.push(name);
    }
};

Object.values(curriculum.curriculumData).flat().forEach(addCourse);
Object.keys(curriculum.subjectImages).forEach(addCourse);

const sql = [];
sql.push('-- Generated by scripts/generate-supabase-seed.js. Do not edit manually.');
sql.push('begin;');
sql.push('');
sql.push(`truncate table
    public.course_images,
    public.category_courses,
    public.curriculum_shortcuts,
    public.portfolio_items,
    public.review_items,
    public.seminars,
    public.courses,
    public.curriculum_categories,
    public.app_settings
restart identity cascade;`);
sql.push('');

const settings = [
    ['brand', site.brand],
    ['location', site.location],
    ['contact', site.contact],
    ['seminar_meta', {
        applicationMethod: site.seminars.applicationMethod,
        all: site.seminars.all
    }]
];

sql.push('insert into public.app_settings (key, value, is_published) values');
sql.push(settings.map(([key, value]) => `    (${quote(key)}, ${json(value)}, true)`).join(',\n') + ';');
sql.push('');

sql.push('insert into public.curriculum_categories (slug, parent_slug, name, course_flow_html, sort_order, is_published) values');
sql.push(categoryRows.map((row) => `    (${quote(row.slug)}, ${nullable(row.parentSlug)}, ${quote(row.name)}, ${quote(row.flow)}, ${row.sortOrder}, true)`).join(',\n') + ';');
sql.push('');

sql.push('insert into public.courses (name, is_published) values');
sql.push(courseNames.map((name) => `    (${quote(name)}, true)`).join(',\n') + ';');
sql.push('');

for (const [categorySlug, names] of Object.entries(curriculum.curriculumData)) {
    sql.push(`insert into public.category_courses (category_slug, course_id, sort_order, is_published)
select ${quote(categorySlug)}, id, course_order, true
from public.courses
join (values
${names.map((name, index) => `    (${quote(name)}, ${index})`).join(',\n')}
) as source(course_name, course_order) on source.course_name = courses.name;`);
    sql.push('');
}

for (const [courseName, images] of Object.entries(curriculum.subjectImages)) {
    if (images.length === 0) continue;
    sql.push(`insert into public.course_images (course_id, image_url, alt_text, sort_order, is_published)
select courses.id, source.image_url, ${quote(`${courseName} 과정 상세 이미지`)}, source.image_order, true
from public.courses
cross join (values
${images.map((url, index) => `    (${quote(url)}, ${index})`).join(',\n')}
) as source(image_url, image_order)
where courses.name = ${quote(courseName)};`);
    sql.push('');
}

sql.push('insert into public.curriculum_shortcuts (label, title, description_lines, target_category_slug, aria_label, sort_order, is_published) values');
sql.push(site.shortcuts.map((item, index) => `    (${quote(item.label)}, ${quote(item.title)}, ${textArray(item.description)}, ${quote(item.target)}, ${quote(item.ariaLabel)}, ${index}, true)`).join(',\n') + ';');
sql.push('');

sql.push('insert into public.portfolio_items (thumbnail_url, detail_image_url, alt_text, sort_order, is_published) values');
sql.push(site.portfolio.map((item, index) => `    (${quote(item.thumbnail)}, ${quote(item.detailImage)}, ${quote(item.alt)}, ${index}, true)`).join(',\n') + ';');
sql.push('');

const reviewRows = [{
    kind: 'hero',
    label: site.reviews.hero.type,
    title: site.reviews.hero.title,
    body: site.reviews.hero.subtitle,
    course: null,
    author: site.reviews.hero.name,
    year: site.reviews.hero.year,
    sortOrder: 0
}, ...site.reviews.items.map((item, index) => ({
    kind: 'item',
    label: item.type,
    title: null,
    body: item.quote,
    course: item.course,
    author: item.name,
    year: null,
    sortOrder: index + 1
}))];

sql.push('insert into public.review_items (kind, label, title, body, course_name, author_name, year_label, sort_order, is_published) values');
sql.push(reviewRows.map((item) => `    (${quote(item.kind)}, ${quote(item.label)}, ${nullable(item.title)}, ${quote(item.body)}, ${nullable(item.course)}, ${quote(item.author)}, ${nullable(item.year)}, ${item.sortOrder}, true)`).join(',\n') + ';');
sql.push('');

sql.push('insert into public.seminars (branch, title, description, event_date_label, application_period_label, image_url, background_class, sort_order, is_published) values');
sql.push(site.seminars.items.map((item, index) => `    (${quote(item.branch)}, ${quote(item.title)}, ${quote(item.description)}, ${quote(item.date)}, ${quote(item.applicationPeriod)}, ${quote(item.image)}, ${quote(item.backgroundClass)}, ${index}, true)`).join(',\n') + ';');
sql.push('');
sql.push('commit;');
sql.push('');

fs.writeFileSync(outputPath, sql.join('\n'), 'utf8');

console.log('[Supabase seed 생성 완료]');
console.log(`- 카테고리: ${categoryRows.length}개`);
console.log(`- 고유 과정: ${courseNames.length}개`);
console.log(`- 과정 연결: ${Object.values(curriculum.curriculumData).flat().length}개`);
console.log(`- 과정 이미지: ${Object.values(curriculum.subjectImages).flat().length}개`);
console.log(`- 바로가기: ${site.shortcuts.length}개`);
console.log(`- 포트폴리오: ${site.portfolio.length}개`);
console.log(`- 후기: ${reviewRows.length}개`);
console.log(`- 세미나: ${site.seminars.items.length}개`);
